// CVE-2024-34055 class (Cyrus): one command with very many literals. MULTIAPPEND reads every
// message before storing them; each one now counts a fixed cost toward the 32 MB cap, so a flood
// of 1-byte messages is cut off with BYE [TOOBIG] after a few thousand, not held by the million.
func TestCVE_2024_34055_ManyAppendLiterals(t *testing.T) {
	t.Parallel()
	_, _, _, ln, cleanup := startIMAPTestServer(t)
	defer cleanup()
	c, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	_ = c.SetDeadline(time.Now().Add(20 * time.Second))
	r := bufio.NewReader(c)
	expectPrefix(t, r, "* OK")
	send(t, c, "l1 LOGIN alice@localhost beaver")
	expectPrefix(t, r, "l1 OK")

	go func() {
		_, _ = c.Write([]byte("a1 APPEND INBOX {1+}\r\nx"))
		chunk := []byte(strings.Repeat(" {1+}\r\nx", 10000))
		for range 100 { // up to a million messages, never ended
			if _, err := c.Write(chunk); err != nil {
				return
			}
		}
	}()
	expectPrefix(t, r, "* BYE [TOOBIG]")
}

// Keywords are atoms and unknown \flags are refused (RFC 3501 9): NUL (CVE-2019-11500 class), "]"
// and friends used to be stored and echoed into FLAGS/PERMANENTFLAGS of every session, and
// "\Bogus" was generated by the server. "Seen" without backslash is a keyword, not \Seen.
func TestStoreRejectsInvalidFlags(t *testing.T) {
	t.Parallel()
	_, _, _, ln, cleanup := startIMAPTestServer(t)
	defer cleanup()
	c, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	_ = c.SetDeadline(time.Now().Add(10 * time.Second))
	r := bufio.NewReader(c)
	expectPrefix(t, r, "* OK")
	send(t, c, "l1 LOGIN alice@localhost beaver")
	expectPrefix(t, r, "l1 OK")
	msg := "From: a@example.org\r\n\r\nz\r\n"
	send(t, c, "a1 APPEND INBOX {"+strconv.Itoa(len(msg))+"+}\r\n"+msg)
	expectPrefix(t, r, "a1 OK")
	send(t, c, "s1 SELECT INBOX")
	skipTo(t, r, "s1 OK")

	for i, flags := range []string{"k\x00w", "k]w", `k"w`, "k{3}w", `\Bogus`} {
		tag := "b" + strconv.Itoa(i)
		send(t, c, tag+" STORE 1 +FLAGS ("+flags+")")
		expectPrefix(t, r, tag+" BAD")
	}
	send(t, c, "k1 STORE 1 FLAGS (Seen)")
	line := readPrefix(t, r, "* FLAGS")
	if strings.Contains(line, `\Bogus`) || strings.Contains(line, "k]w") {
		t.Fatalf("invalid flag announced: %q", line)
	}
	expectPrefix(t, r, "* OK [PERMANENTFLAGS")
	if line := readPrefix(t, r, "* 1 FETCH"); !strings.Contains(line, " Seen)") || strings.Contains(line, `\Seen`) {
		t.Fatalf(`"Seen" keyword not kept as a keyword: %q`, line)
	}
	expectPrefix(t, r, "k1 OK")
}

// readPrefix reads one line, fails unless it starts with prefix, and returns it.
func readPrefix(t *testing.T, r *bufio.Reader, prefix string) string {
	t.Helper()
	line, err := r.ReadString('\n')
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(line, prefix) {
		t.Fatalf("line %q want prefix %q", line, prefix)
	}
	return line
}

// skipTo reads lines until one starts with prefix.
func skipTo(t *testing.T, r *bufio.Reader, prefix string) {
	t.Helper()
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			t.Fatal(err)
		}
		if strings.HasPrefix(line, prefix) {
			return
		}
	}
}

// Idle connections that never log in are capped per client address: 200 of them from one IP used
// to fill the listener and lock everybody out for 30 minutes. Logging in frees the slot.
func TestPreAuthConnectionsPerIP(t *testing.T) {
	t.Parallel()
	_, _, _, ln, cleanup := startIMAPTestServer(t)
	defer cleanup()
	dial := func() (net.Conn, *bufio.Reader) {
		c, err := net.Dial("tcp", ln.Addr().String())
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { c.Close() })
		_ = c.SetDeadline(time.Now().Add(10 * time.Second))
		return c, bufio.NewReader(c)
	}
	var first net.Conn
	var firstR *bufio.Reader
	for i := range 10 {
		c, r := dial()
		expectPrefix(t, r, "* OK")
		if i == 0 {
			first, firstR = c, r
		}
	}
	_, r := dial()
	expectPrefix(t, r, "* BYE [UNAVAILABLE]")

	send(t, first, "l1 LOGIN alice@localhost beaver")
	expectPrefix(t, firstR, "l1 OK")
	_, r = dial()
	expectPrefix(t, r, "* OK")
}
