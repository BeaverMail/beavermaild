-- BeaverMail storage schema v1 (MySQL / MariaDB).
-- Keys use a 255-byte prefix index (Stalwart-compatible). Values are LONGBLOB envelopes.

CREATE TABLE IF NOT EXISTS `_beaver_schema_version` (
    id TINYINT NOT NULL,
    version INT NOT NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `m` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `i` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `n` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `t` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `l` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `a` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `u` (
    k TINYBLOB NOT NULL,
    v LONGBLOB NOT NULL,
    PRIMARY KEY (k(255))
) ENGINE=InnoDB;
