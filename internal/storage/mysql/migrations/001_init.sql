-- BeaverMail storage schema v1 (MySQL).

CREATE TABLE IF NOT EXISTS _beaver_schema_version (
    id TINYINT PRIMARY KEY CHECK (id = 1),
    version INT NOT NULL
);

CREATE TABLE IF NOT EXISTS m (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS i (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS n (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS t (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS l (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS a (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
CREATE TABLE IF NOT EXISTS u (k VARBINARY(767) PRIMARY KEY, v LONGBLOB NOT NULL);
