-- BeaverMail storage schema v1 (PostgreSQL).

CREATE TABLE IF NOT EXISTS _beaver_schema_version (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    version INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS m (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS i (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS n (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS t (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS l (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS a (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS u (k BYTEA PRIMARY KEY, v BYTEA NOT NULL);
