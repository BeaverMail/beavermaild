// Package license verifies Ed25519-signed plugin license files offline.
//
// A license file is JSON: {"payload": "<license JSON>", "signature": "<base64 Ed25519 signature of payload>"}.
// The payload is kept as a string so the signed bytes need no canonical encoding.
// Verification never touches the network.
package license

import (
	"crypto/ed25519"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"
)

// Environment the host sets for every plugin process (CLI, admin, daemon).
const (
	// EnvLicensesDir is the directory holding <plugin>.lic files (next to config.json).
	EnvLicensesDir = "BEAVER_LICENSES_DIR"
	// EnvInstallID is the installation id generated by beaver init.
	EnvInstallID = "BEAVER_INSTALL_ID"
)

// License models.
const (
	ModelOneshot   = "oneshot"   // one-time price, no expiry
	ModelPerpetual = "perpetual" // builds released up to UpdatesUntil keep working forever
)

// DateLayout is the format of UpdatesUntil and Product.Released.
const DateLayout = "2006-01-02"

// License is the signed payload. Exactly one scope is set: Domains or InstallID.
type License struct {
	Plugin       string   `json:"plugin"`
	Model        string   `json:"model"`
	Licensee     string   `json:"licensee"`
	Domains      []string `json:"domains,omitempty"`
	InstallID    string   `json:"install_id,omitempty"`
	UpdatesUntil string   `json:"updates_until,omitempty"`
}

// Product is what a paid plugin build embeds.
type Product struct {
	Plugin    string            // id, also the license file name: <Plugin>.lic
	PublicKey ed25519.PublicKey // vendor signing key
	Released  string            // release date of this build (DateLayout); checked against UpdatesUntil
	BuyURL    string            // shown when the license is missing or invalid
}

// ErrMissing reports that no license file exists for the plugin.
var ErrMissing = errors.New("license file not found")

// ErrNotCovered reports a perpetual license whose update window ended before this build was released.
var ErrNotCovered = errors.New("license does not cover this version")

type file struct {
	Payload   string `json:"payload"`
	Signature string `json:"signature"`
}

// Sign builds a license file. Used by the vendor's issuing tool and by tests.
func Sign(priv ed25519.PrivateKey, lic License) ([]byte, error) {
	payload, err := json.Marshal(lic)
	if err != nil {
		return nil, err
	}
	sig := ed25519.Sign(priv, payload)
	return json.MarshalIndent(file{Payload: string(payload), Signature: base64.StdEncoding.EncodeToString(sig)}, "", "  ")
}

// Path returns the license file path for p under dir.
func (p Product) Path(dir string) string {
	return filepath.Join(dir, p.Plugin+".lic")
}

// Verify checks signature, plugin id, model, scope and update window of a license file.
func (p Product) Verify(data []byte, installID string) (License, error) {
	var f file
	if err := json.Unmarshal(data, &f); err != nil {
		return License{}, fmt.Errorf("malformed license file: %w", err)
	}
	sig, err := base64.StdEncoding.DecodeString(f.Signature)
	if err != nil || len(p.PublicKey) != ed25519.PublicKeySize || !ed25519.Verify(p.PublicKey, []byte(f.Payload), sig) {
		return License{}, errors.New("bad license signature")
	}
	var lic License
	if err := json.Unmarshal([]byte(f.Payload), &lic); err != nil {
		return License{}, fmt.Errorf("malformed license payload: %w", err)
	}
	if lic.Plugin != p.Plugin {
		return lic, fmt.Errorf("license is for plugin %q, not %q", lic.Plugin, p.Plugin)
	}
	if (len(lic.Domains) == 0) == (lic.InstallID == "") {
		return lic, errors.New("license must name either domains or an install id")
	}
	if lic.InstallID != "" && lic.InstallID != installID {
		return lic, fmt.Errorf("license is for installation %s, this is %s", lic.InstallID, orNone(installID))
	}
	switch lic.Model {
	case ModelOneshot:
	case ModelPerpetual:
		until, err := time.Parse(DateLayout, lic.UpdatesUntil)
		if err != nil {
			return lic, fmt.Errorf("license updates_until %q: %w", lic.UpdatesUntil, err)
		}
		released, err := time.Parse(DateLayout, p.Released)
		if err != nil {
			return lic, fmt.Errorf("plugin release date %q: %w", p.Released, err)
		}
		if released.After(until) {
			return lic, fmt.Errorf("%w: it covers versions released until %s, this one was released %s", ErrNotCovered, lic.UpdatesUntil, p.Released)
		}
	default:
		return lic, fmt.Errorf("unknown license model %q", lic.Model)
	}
	return lic, nil
}

// Load reads and verifies the license from the directory and install id the host passes in the environment.
func (p Product) Load() (License, error) {
	return p.LoadFrom(os.Getenv(EnvLicensesDir), os.Getenv(EnvInstallID))
}

// LoadFrom reads and verifies <dir>/<Plugin>.lic.
func (p Product) LoadFrom(dir, installID string) (License, error) {
	if dir == "" {
		return License{}, ErrMissing
	}
	data, err := os.ReadFile(p.Path(dir))
	if errors.Is(err, os.ErrNotExist) {
		return License{}, ErrMissing
	}
	if err != nil {
		return License{}, err
	}
	return p.Verify(data, installID)
}

// Require loads the license or prints a readable message to stderr and exits 1.
// It only stops the plugin; it never touches mail data.
func (p Product) Require() License {
	lic, err := p.Load()
	if err != nil {
		fmt.Fprintln(os.Stderr, p.Message(err))
		os.Exit(1)
	}
	return lic
}

// Message explains a license error to the operator, with where to put the file and where to buy one.
func (p Product) Message(err error) string {
	msg := fmt.Sprintf("plugin %s: %v", p.Plugin, err)
	if errors.Is(err, ErrMissing) {
		dir := os.Getenv(EnvLicensesDir)
		if dir == "" {
			dir = "the licenses directory next to config.json"
		}
		msg = fmt.Sprintf("plugin %s needs a license: put %s.lic in %s", p.Plugin, p.Plugin, dir)
	}
	if p.BuyURL != "" {
		msg += "\nbuy a license: " + p.BuyURL
	}
	return msg
}

// AllowsDomain reports whether the license covers domain (always true for an install-scoped license).
func (l License) AllowsDomain(domain string) bool {
	if l.InstallID != "" {
		return true
	}
	domain = strings.TrimSuffix(strings.TrimSpace(domain), ".")
	return slices.ContainsFunc(l.Domains, func(d string) bool { return strings.EqualFold(d, domain) })
}

// AllowsAccount reports whether the license covers the domain of an email address.
func (l License) AllowsAccount(email string) bool {
	at := strings.LastIndexByte(email, '@')
	return at >= 0 && l.AllowsDomain(email[at+1:])
}

func orNone(s string) string {
	if s == "" {
		return "unknown"
	}
	return s
}
